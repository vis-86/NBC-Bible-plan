/**
 * Размечает номера стихов в сыром тексте главы как `**N**` для ReactMarkdown.
 *
 * Формат данных: стихи склеены в одну строку ("1 текст. 2 текст ..."), отдельного
 * разделителя у номера стиха нет. Наивное «любое число+пробел = стих» ошибочно
 * помечало числа внутри текста («40 дней», «7 раз») — они получали номер стиха,
 * жирный шрифт и лишний перенос при verse_per_line.
 *
 * Правило (проверено на всех 1189 главах датасета — 31005 стихов, 0 ложных скачков):
 * число считается номером стиха, только если оно
 *   1) стоит в начале строки / после пунктуации (перед ним НЕ буква и НЕ цифра), И
 *   2) строго больше предыдущего принятого номера, но не более чем на MAX_VERSE_GAP.
 * Пункт 1 отсекает «40 дней» (перед 40 — буква). Пункт 2 отсекает мелкие числа
 * внутри стиха (они ≤ текущего номера) и «числа-скачки» после пунктуации («7 раз»),
 * при этом переживая реальные пропуски нумерации Синодального (объединённые стихи,
 * напр. 23→25): максимальный реальный разрыв в датасете — 3.
 */
// Максимальный разрыв между соседними номерами стихов в датасете (объединённые стихи).
const MAX_VERSE_GAP = 3;

export function markVerseNumbers(text: string): string {
  const parts = text.split(/(\d+\s+)/g);
  let lastChar = '';
  let lastVerse = -1;
  let out = '';

  for (const part of parts) {
    const verseToken = /^(\d+)\s+$/.exec(part);
    if (verseToken) {
      const n = Number(verseToken[1]);
      const atBoundary = lastChar === '' || !/[\p{L}\p{N}]/u.test(lastChar);
      // Первый номер главы (lastVerse=-1) принимаем без верхней границы; далее —
      // строго возрастающий номер в пределах реального разрыва нумерации.
      const withinRange =
        lastVerse === -1 ? true : n > lastVerse && n <= lastVerse + MAX_VERSE_GAP;
      if (atBoundary && withinRange) {
        lastVerse = n;
        out += `**${n}** `;
        // Номер стиха — не текст: границу для следующего числа задаёт текст стиха ниже,
        // поэтому lastChar здесь не трогаем.
        continue;
      }
    }
    // Обычный текст ИЛИ число внутри стиха — оставляем как есть.
    out += part;
    const trimmed = part.replace(/\s+$/, '');
    if (trimmed.length > 0) lastChar = trimmed.slice(-1);
  }

  return out;
}
