import { describe, expect, it } from 'vitest';
import { markVerseNumbers } from './verse-markup';

describe('markVerseNumbers', () => {
  it('размечает последовательные номера стихов', () => {
    expect(markVerseNumbers('1 Первый. 2 Второй. 3 Третий.')).toBe(
      '**1** Первый. **2** Второй. **3** Третий.'
    );
  });

  it('не считает стихом число внутри текста (перед ним буква)', () => {
    // «40 дней» не должно стать номером стиха — это и есть баг over-match.
    const out = markVerseNumbers('1 Ходил он 40 дней. 2 И вернулся.');
    expect(out).toBe('**1** Ходил он 40 дней. **2** И вернулся.');
  });

  it('не считает стихом мелкое число внутри стиха, даже после пунктуации', () => {
    // «7» после двоеточия, но 7 <= текущего номера стиха (1) → не стих.
    const out = markVerseNumbers('1 Сказал он: 7 раз прости. 2 Аминь.');
    expect(out).toBe('**1** Сказал он: 7 раз прости. **2** Аминь.');
  });

  it('переживает пропуск нумерации (объединённые стихи Синодального 23→25)', () => {
    const out = markVerseNumbers('22 Двадцать два. 23 Двадцать три. 25 Двадцать пять.');
    expect(out).toBe('**22** Двадцать два. **23** Двадцать три. **25** Двадцать пять.');
  });

  it('размечает надписание псалма (стих 0) и первый стих', () => {
    const out = markVerseNumbers('0 Псалом Давида.\n\n1 Блажен муж.');
    expect(out).toBe('**0** Псалом Давида.\n\n**1** Блажен муж.');
  });

  it('число, склеенное с текстом или в HTML-сущности, не трогает', () => {
    // &#769; (ударение) — «769» без завершающего пробела и перед ним «#» → не стих.
    const out = markVerseNumbers('1 Сло&#769;во Его. 2 Далее.');
    expect(out).toBe('**1** Сло&#769;во Его. **2** Далее.');
  });
});
