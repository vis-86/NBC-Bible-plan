'use client';

export interface SongToolStackProps {
  /** Слоты снизу вверх. Первый элемент массива — самый нижний. */
  children: React.ReactNode;
}

/**
 * Правый нижний край песни — единая точка входа для инструментов (сейчас автоскролл,
 * дальше карандаш заметок M10). Горизонтальный бюджет фиксирован (48px + поле) и не
 * растёт с числом слотов — стек растёт вверх (`flex-col-reverse`).
 *
 * Стек НЕ прячется вместе с шапкой: автоскролл включают именно во время чтения, и
 * уезжающая на первом же движении листа кнопка делала инструмент недоступным.
 * Скрывают его только шторки (условие рендера на стороне экрана песни).
 *
 * Исключение — фокус-режим: пока автоскролл ИГРАЕТ, в стеке остаётся только его
 * собственный FAB (им и выключают режим), остальные слоты скрыты — тот же принцип,
 * что и у активного инструмента. Условие рендера живёт на стороне страницы.
 *
 * Контракт на будущее (карандаш M10): активный инструмент забирает правый край целиком,
 * остальные слоты в это время скрыты — не выводить два раскрытых инструмента одновременно.
 */
export function SongToolStack({ children }: SongToolStackProps) {
  return (
    <div
      data-song-tool-stack
      className="pointer-events-none absolute right-3.5 bottom-3.5 flex flex-col-reverse items-center gap-2.5 pb-safe"
    >
      {children}
    </div>
  );
}
