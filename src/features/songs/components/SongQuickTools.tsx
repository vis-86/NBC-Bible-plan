'use client';

import { cn } from '@/shared/utils/cn';

export interface SongQuickToolsProps {
  /** Те же контролы, что живут в правом слоте шапки: тональность и настройки просмотра. */
  children: React.ReactNode;
  className?: string;
}

/**
 * Управление песней (тональность + настройки), которое занимает место уехавшей шапки.
 * Без него скролл листа отнимал у читающего оба контрола сразу, а вернуть их можно было
 * только прокруткой вверх или тапом — на служении это лишние движения ровно в тот момент,
 * когда нужно поднять тональность.
 *
 * Геометрия повторяет правый слот `PageHeader` (`px-4` + `-mr-2`, `min-h-[52px]` с
 * вертикальным центрированием под `pt-safe`): кнопки обязаны оказаться пиксель-в-пиксель
 * там же, где стояли в шапке, иначе уход шапки читается как перескок кнопок. Своей подложки нет
 * намеренно — плашка под кнопками выглядела чужим островком поверх текста.
 *
 * Контролы существуют в ОДНОМ экземпляре: показывается это только при спрятанной шапке
 * (условие рендера — на стороне страницы), поэтому в DOM всегда ровно один
 * `SongKeyPicker` (на этом держатся e2e-селекторы).
 *
 * Проявление — `opacity` + `margin-top`, НЕ `transform`, и без `backdrop-filter`. И то,
 * и другое делает элемент контейнером для `position: fixed`, а шторка транспонирования
 * рендерится внутри `SongKeyPicker` именно так — с любым из них она схлопывается в
 * габариты кнопки (тот же инвариант, по которому шапка уезжает через `top`).
 */
export function SongQuickTools({ children, className }: SongQuickToolsProps) {
  return (
    <div
      data-song-quick-tools
      // pt-safe: под бровью выреза, а не под ней самой. Высота — `min-h`, как у шапки:
      // с жёсткой `h-[52px]` отступ выреза съедал бы её изнутри (border-box), и на
      // iPhone кнопкам оставалось несколько пикселей — они уезжали под бровь.
      // Обёртка прозрачна для указателя — тап мимо кнопок обязан долетать до листа.
      className="pointer-events-none absolute inset-x-0 top-0 z-30 flex min-h-[52px] items-center justify-end px-4 pt-safe pb-0"
    >
      <div
        className={cn(
          'pointer-events-auto -mr-2 flex h-11 min-w-11 items-center justify-end',
          'animate-song-quick-tools-in',
          className,
        )}
      >
        {children}
      </div>
    </div>
  );
}
