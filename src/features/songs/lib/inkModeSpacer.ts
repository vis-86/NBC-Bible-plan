/**
 * Отступ под плашку режима пометок (§6): пока режим включён, над листом появляется
 * пустое место высотой с плашку — первые строки можно опустить под неё и рисовать.
 *
 * Отступ живёт в скролл-контейнере, а не в листе: высота страницы не меняется, и
 * страницы не переразбиваются на входе в режим.
 */

/**
 * `scrollTop` после того, как отступ появился (`entering`) или исчез.
 *
 * - В начале песни (прокрутка меньше отступа) лист на входе отъезжает вниз: ради
 *   этого отступ и заведён — первые строки сразу выходят из-под плашки.
 * - В середине песни прокрутка компенсируется: лист стоит на месте, текст под
 *   пальцами не прыгает.
 * - На выходе отступ снимается с прокрутки, насколько она позволяет.
 */
export function inkSpacerScrollTop(scrollTop: number, spacer: number, entering: boolean): number {
  if (entering) return scrollTop < spacer ? scrollTop : scrollTop + spacer;
  return Math.max(0, scrollTop - spacer);
}
