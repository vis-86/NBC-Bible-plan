/**
 * Прокрутка на входе в режим пометок и выходе из него (§6).
 *
 * В режиме шапка песни уезжает, и верхний отступ листа под неё (`freed`) снимается —
 * лист получает её место. Без поправки прокрутки снятие отступа сдвигало бы текст
 * вверх ровно в тот момент, когда человек целится пером в строку.
 *
 * Высоту страницы-листа отступы не меняют: страница компенсирует их через
 * `SongView.viewportExtraPadding`, иначе вход в режим переразбивал бы листы.
 */

/**
 * `scrollTop` после снятия (`entering`) или возврата отступа шапки.
 *
 * - В середине песни прокрутка компенсируется: текст стоит на месте.
 * - В начале песни компенсировать нечем — лист поднимается на освободившееся место,
 *   ради которого шапку и прячем.
 * - На выходе из начала песни лист возвращается в начало, а не под вернувшуюся шапку.
 */
export function inkModeScrollTop(scrollTop: number, freed: number, entering: boolean): number {
  if (entering) return Math.max(0, scrollTop - freed);
  return scrollTop === 0 ? 0 : scrollTop + freed;
}
