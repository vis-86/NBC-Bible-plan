/**
 * Классификация токенов в квадратных скобках (§3.1 спеки).
 *
 * В корпусе `[...]` — не всегда аккорд: там же живут тактовая черта `[|]` и текстовые
 * пометки `[(пауза)]`. Без этой классификации транспозиция ломает их обе, поэтому
 * классификатор отделён от рендера и от самой транспозиции.
 *
 * Валидации аккорда здесь нет намеренно: битые данные корпуса (`[C#mсть.]`) остаются
 * `chord` и рендерятся как есть (§2) — падать на данных нельзя.
 */

export type Marker =
  | { kind: 'chord'; text: string }
  | { kind: 'bar' }
  | { kind: 'note'; text: string };

/** Содержимое маркера без квадратных скобок: `[C/G]` → `C/G`. */
export function classifyMarker(raw: string): Marker {
  const text = raw.trim();
  if (text === '|') return { kind: 'bar' };
  if (/^\(.*\)$/.test(text)) return { kind: 'note', text };
  return { kind: 'chord', text };
}
