/**
 * Группировка строк секции для склейки соседних строк в одну визуальную.
 *
 * Здесь решается только КАКИЕ строки вообще имеют право склеиться. Условие
 * «влезает по ширине» считает не JS, а `flex-wrap` в `songs.css`: измерять ширину
 * в React пришлось бы на каждый ресайз, смену шрифта и транспозицию — CSS делает
 * то же самое бесплатно и всегда синхронно с раскладкой.
 *
 * Пустая строка внутри секции — смысловая отбивка: она идёт своей группой и
 * обнуляет счёт пар. Иначе склейка съела бы отбивку (пустая строка нулевой ширины
 * прилипла бы к соседней) и сдвинула бы разбивку всех следующих строк на пары.
 */
export function groupSongLinePairs(lines: string[]): number[][] {
  const groups: number[][] = [];
  let pair: number[] | null = null;

  lines.forEach((line, index) => {
    if (line.trim() === '') {
      groups.push([index]);
      pair = null;
      return;
    }
    if (pair && pair.length < 2) {
      pair.push(index);
      return;
    }
    pair = [index];
    groups.push(pair);
  });

  return groups;
}
